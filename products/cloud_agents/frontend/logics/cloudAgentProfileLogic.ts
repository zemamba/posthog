export interface CloudAgentProfileLogicProps {
    /** The profile ID, or `new` for the create form. */
    id: string
}

export interface ProfileForm {
    name: string
    description: string
    repository: string
    branch: string
    model: string | null
    size: SizeNameEnumApi | null
    inference: InferenceModeEnumApi | null
    instructions: string
    tags: string[]
}

const EMPTY_PROFILE: ProfileForm = {
    name: '',
    description: '',
    repository: '',
    branch: '',
    model: null,
    size: null,
    inference: null,
    instructions: '',
    tags: [],
}

function toForm(profile: ProfileApi): ProfileForm {
    return {
        name: profile.name,
        description: profile.description,
        repository: profile.repository ?? '',
        branch: profile.branch ?? '',
        model: profile.model ?? null,
        size: profile.size ?? null,
        inference: profile.inference ?? null,
        instructions: profile.instructions ?? '',
        tags: profile.tags,
    }
}

function toRequest(form: ProfileForm): ProfileCreateApi {
    return {
        name: form.name.trim(),
        description: form.description.trim(),
        repository: form.repository.trim() || null,
        branch: form.branch.trim() || null,
        model: form.model,
        size: form.size,
        inference: form.inference,
        instructions: form.instructions.trim() || null,
        tags: form.tags,
    }
}

