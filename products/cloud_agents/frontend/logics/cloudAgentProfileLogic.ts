export const cloudAgentProfileLogic = kea<cloudAgentProfileLogicType>([
    props({} as CloudAgentProfileLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentProfileLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        profile: [
            null as ProfileApi | null,
            {
                loadProfile: async (): Promise<ProfileApi> =>
                    await cloudAgentsProfilesRetrieve(String(values.currentProjectId), props.id),
            },
        ],
    })),
    reducers({
        profileLoadError: [
            null as 'not_found' | 'failed' | null,
            {
                loadProfileSuccess: () => null,
                loadProfileFailure: (_, { errorObject }) => (errorObject?.status === 404 ? 'not_found' : 'failed'),
            },
        ],
    }),
    forms(({ actions, props, values }) => ({
        profileForm: {
            defaults: EMPTY_PROFILE,
            errors: ({ name, repository }) => ({
                name: !name.trim() ? 'Give the profile a name' : undefined,
                repository:
                    repository.trim() && !/^[\w.-]+\/[\w.-]+$/.test(repository.trim())
                        ? 'Use the form owner/name, for example acme/web'
                        : undefined,
            }),
            submit: async (form) => {
                const isNew = props.id === 'new'
                const projectId = String(values.currentProjectId)
                try {
                    if (isNew) {
                        await cloudAgentsProfilesCreate(projectId, toRequest(form))
                    } else {
                        await cloudAgentsProfilesPartialUpdate(projectId, props.id, toRequest(form))
                    }
                } catch (error) {
                    const { attr, detail } = error as { attr?: string | null; detail?: string | null }
                    if (attr && attr in form && detail) {
                        actions.setProfileFormManualErrors({ [attr]: detail })
                    } else {
                        lemonToast.error(detail || 'Could not save the profile. Try again.')
                    }
                    throw error
                }
                // pinned: analytics event and property names. A rename breaks the dashboards that read them.
                posthog.capture('cloud_agents_profile_saved', { is_new: isNew })
                lemonToast.success(`Saved the profile "${form.name.trim()}"`)
                router.actions.push(urls.cloudAgentProfiles())
            },
        },
    })),
    selectors({
        isNew: [() => [(_, props) => props.id], (id): boolean => id === 'new'],
    }),
    listeners(({ actions }) => ({
        loadProfileSuccess: ({ profile }) => {
            if (profile) {
                actions.resetProfileForm(toForm(profile))
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.id !== 'new') {
            actions.loadProfile()
        }
    }),
])
