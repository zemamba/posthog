import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import {
    usersIntegrationsInferenceCredentialsCreate,
    usersIntegrationsInferenceCredentialsDestroy,
    usersIntegrationsInferenceCredentialsRetrieve,
} from '~/generated/core/api'
import type { InferenceCredentialKindEnumApi, UserInferenceCredentialApi } from '~/generated/core/api.schemas'

import { describeCredentialError } from '../utils/errors'

/** The user segment of the credentials URL. `@me` is the signed-in user. */
const CURRENT_USER = '@me'

type PerKind<T> = Partial<Record<InferenceCredentialKindEnumApi, T>>

