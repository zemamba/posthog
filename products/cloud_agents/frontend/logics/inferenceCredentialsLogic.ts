/** The model provider credentials of the signed-in user. Each person connects their own. */
export const inferenceCredentialsLogic = kea<inferenceCredentialsLogicType>([
    path(['products', 'cloud_agents', 'frontend', 'logics', 'inferenceCredentialsLogic']),
    actions({
        setSecret: (kind: InferenceCredentialKindEnumApi, secret: string) => ({ kind, secret }),
        connectCredential: (kind: InferenceCredentialKindEnumApi) => ({ kind }),
        connectCredentialDone: (kind: InferenceCredentialKindEnumApi, error: string | null) => ({ kind, error }),
        removeCredential: (kind: InferenceCredentialKindEnumApi) => ({ kind }),
        removeCredentialDone: (kind: InferenceCredentialKindEnumApi) => ({ kind }),
    }),
    loaders({
        credentials: [
            null as UserInferenceCredentialApi[] | null,
            {
                loadCredentials: async (): Promise<UserInferenceCredentialApi[]> =>
                    (await usersIntegrationsInferenceCredentialsRetrieve(CURRENT_USER)).results,
            },
        ],
    }),
    reducers({
        credentialsLoadFailed: [false, { loadCredentials: () => false, loadCredentialsFailure: () => true }],
        secrets: [
            {} as PerKind<string>,
            {
                setSecret: (state, { kind, secret }) => ({ ...state, [kind]: secret }),
                connectCredentialDone: (state, { kind, error }) => (error ? state : { ...state, [kind]: '' }),
            },
        ],
        connecting: [
            {} as PerKind<boolean>,
            {
                connectCredential: (state, { kind }) => ({ ...state, [kind]: true }),
                connectCredentialDone: (state, { kind }) => ({ ...state, [kind]: false }),
            },
        ],
        connectErrors: [
            {} as PerKind<string | null>,
            {
                connectCredential: (state, { kind }) => ({ ...state, [kind]: null }),
                connectCredentialDone: (state, { kind, error }) => ({ ...state, [kind]: error }),
            },
        ],
        removing: [
            {} as PerKind<boolean>,
            {
                removeCredential: (state, { kind }) => ({ ...state, [kind]: true }),
                removeCredentialDone: (state, { kind }) => ({ ...state, [kind]: false }),
            },
        ],
    }),
    selectors({
        credentialsByKind: [
            (s) => [s.credentials],
            (credentials: UserInferenceCredentialApi[] | null): PerKind<UserInferenceCredentialApi> =>
                Object.fromEntries((credentials ?? []).map((credential) => [credential.kind, credential])),
        ],
    }),
    listeners(({ actions, values }) => ({
        connectCredential: async ({ kind }) => {
            // pinned: analytics event and property names. A rename breaks the dashboards that read them.
            posthog.capture('cloud_agents_credential_connect_clicked', { kind })
            const secret = (values.secrets[kind] ?? '').trim()
            if (!secret) {
                actions.connectCredentialDone(kind, 'Paste the key first.')
                return
            }
            try {
                await usersIntegrationsInferenceCredentialsCreate(CURRENT_USER, { kind, secret })
                actions.connectCredentialDone(kind, null)
                lemonToast.success('Connected your model provider')
                actions.loadCredentials()
            } catch (error) {
                actions.connectCredentialDone(kind, describeCredentialError(error))
            }
        },
        removeCredential: async ({ kind }) => {
            try {
                await usersIntegrationsInferenceCredentialsDestroy(CURRENT_USER, kind)
                lemonToast.success('Removed the credential')
                actions.loadCredentials()
            } catch {
                lemonToast.error('Could not remove the credential. Try again.')
            } finally {
                actions.removeCredentialDone(kind)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadCredentials()
    }),
])
